// 1. Append to en/general.js
const enGeneralPath = './client/src/constants/languages/en/general.js';
let enGeneralContent = fs.readFileSync(enGeneralPath, 'utf8');

// Build EN additions
const enAdditions = {};
Object.assign(enAdditions, enTranslationsForMissingEs);
for (const [k, v] of Object.entries(commonCodeTranslations)) {
    enAdditions[k] = v.en;
}

// Filter out keys already in enGeneralContent
const enKeysToInsert = Object.entries(enAdditions).filter(([k]) => !enGeneralContent.includes(`${k}:`));
if (enKeysToInsert.length > 0) {
    const insertBlock = '\n    // Synced translations\n' + enKeysToInsert.map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`).join('\n') + '\n';
    enGeneralContent = enGeneralContent.replace(/};\s*$/, `${insertBlock}};\n`);
    fs.writeFileSync(enGeneralPath, enGeneralContent, 'utf8');
    console.log(`Added ${enKeysToInsert.length} keys to en/general.js`);
}

